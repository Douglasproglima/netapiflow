// Writes src/app/core/version.ts from NETAPIFLOW_VERSION, set by
// NetApiFlow.Dashboard.csproj's BuildAngularClient target from the .csproj's own <Version>
// (Directory.Build.props). No API contract involved: this is a build-time constant, not a route.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const version = process.env.NETAPIFLOW_VERSION ?? '0.0.0';
const outputPath = fileURLToPath(new URL('../src/app/core/version.ts', import.meta.url));

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-version.mjs — do not edit by hand.\nexport const DASHBOARD_VERSION = '${version}';\n`,
);

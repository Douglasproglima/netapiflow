const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const TOKENS_PATH = path.join(REPO_ROOT, 'docs', 'brand', 'tokens.md');
const GUIDE_PATH = path.join(REPO_ROOT, 'docs', 'design', 'flow-workspace', 'guide.md');
const OUTPUT_PATH = path.join(REPO_ROOT, 'DESIGN.md');

function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function extractSection(markdown, headingPattern) {
  const lines = markdown.split('\n');
  const startIndex = lines.findIndex((line) => headingPattern.test(line));
  if (startIndex === -1) {
    throw new Error(`Section not found: ${headingPattern}`);
  }

  const headingLevel = lines[startIndex].match(/^(#+)/)[1].length;
  let endIndex = lines.length;
  for (let i = startIndex + 1; i < lines.length; i++) {
    const match = lines[i].match(/^(#+)\s/);
    if (match && match[1].length <= headingLevel) {
      endIndex = i;
      break;
    }
  }

  return lines.slice(startIndex + 1, endIndex).join('\n');
}

function parseTable(block) {
  return block
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.startsWith('|'))
    .filter((line) => !/^\|\s*-+\s*\|/.test(line))
    .map((line) =>
      line
        .slice(1, -1)
        .split('|')
        .map((cell) => cell.trim().replace(/`/g, '')),
    )
    .slice(1); // drop header row
}

function lookup(rows, key) {
  const row = rows.find((cells) => cells[0] === key);
  if (!row) {
    throw new Error(`Row not found: ${key}`);
  }
  return row;
}

function nth(rows, index) {
  const row = rows[index];
  if (!row) {
    throw new Error(`Row not found at index ${index}`);
  }
  return row;
}

function ratio(value) {
  return value.replace(',', '.');
}

function prose(value) {
  return value
    .replace(/tabular-nums/g, 'tabular nums')
    .replace(/letter-spacing:\s*/g, 'letter-spacing ')
    .replace(/\be\b/g, 'and');
}

